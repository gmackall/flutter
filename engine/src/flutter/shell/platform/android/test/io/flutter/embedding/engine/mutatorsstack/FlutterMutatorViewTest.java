  // A condensed version of what impellerc emits with --sksl for a filter shader (see
  // engine/src/flutter/impeller/compiler/spirv_sksl.cc), after the engine's AGSL adaptation
  // (u_texture_size is declared as float2 instead of half2).
  //
  // Note that Robolectric's native RuntimeShader uses an older version of Skia that doesn't support
  // `shader.eval()`, so tests that need it to compile run with legacy graphics.
  private static final String FILTER_AGSL =
      "// This SkSL shader is autogenerated by spirv-cross.\n"
          + "float4 flutter_FragCoord;\n"
          + "uniform vec2 u_size;\n"
          + "uniform float u_strength;\n"
          + "uniform shader u_texture;\n"
          + "uniform float2 u_texture_size;\n"
          + "vec4 frag_color;\n"
          + "vec2 FLT_flutter_local_FlutterFragCoord()\n"
          + "{\n"
          + "    return flutter_FragCoord.xy;\n"
          + "}\n"
          + "float FLT_flutter_local_ease(float t, float d)\n"
          + "{\n"
          + "    return mix(1.0, t * d, 0.7);\n"
          + "}\n"
          + "void FLT_main()\n"
          + "{\n"
          + "    vec2 uv = FLT_flutter_local_FlutterFragCoord() / u_size;\n"
          + "    bool isVertical = u_strength != 0.0;\n"
          + "    float param = uv.y;\n"
          + "    float param_1 = abs(u_strength);\n"
          + "    uv.y = isVertical ? (param / FLT_flutter_local_ease(param, param_1)) : uv.y;\n"
          + "    frag_color = u_texture.eval(u_texture_size * ( uv));\n"
          + "}\n"
          + "half4 main(float2 iFragCoord)\n"
          + "{\n"
          + "      flutter_FragCoord = float4(iFragCoord, 0, 0);\n"
          + "      FLT_main();\n"
          + "      return frag_color;\n"
          + "}\n";

  private static final long FILTER_PROGRAM_ID = 1234;

  private static void registerFilterProgram() {
    FlutterMutatorsStack.registerRuntimeShaderProgram(
        FILTER_PROGRAM_ID,
        FILTER_AGSL,
        "u_texture",
        new String[] {"u_size", "u_strength", "u_texture_size"},
        new int[] {2, 1, 2});
  }

  private static FlutterMutatorsStack makeStackWithFilter(
      float strength, int left, int top, int right, int bottom) {
    final FlutterMutatorsStack stack = new FlutterMutatorsStack();
    final float width = right - left;
    final float height = bottom - top;
    stack.pushRuntimeShaderFilter(
        FILTER_PROGRAM_ID,
        new float[] {width, height, strength, width, height},
        left,
        top,
        right,
        bottom);
    return stack;
  }

