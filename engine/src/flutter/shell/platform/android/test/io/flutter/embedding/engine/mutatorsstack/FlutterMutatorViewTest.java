  @Test
  public void onTouchEvent_delegatesToGestureTrackerAndRequestsUnbufferedOnMove() {
    final AndroidTouchProcessor touchProcessor = mock(AndroidTouchProcessor.class);
    final MotionEvent[] lastRequestedEvent = new MotionEvent[1];
    final FlutterMutatorView view =
        new FlutterMutatorView(ctx, 1.0f, touchProcessor) {
          @Override
          void requestUnbuffered(MotionEvent event) {
            lastRequestedEvent[0] = event;
          }
        };

    // Before Flutter wins the arena: touches are buffered.
    final MotionEvent downEvent =
        MotionEvent.obtain(100, 100, MotionEvent.ACTION_DOWN, 0.0f, 0.0f, 0);
    view.onTouchEvent(downEvent);
    assertTrue(view.isGestureActive());
    assertEquals(100, view.getCurrentDownTime());
    assertNull(lastRequestedEvent[0]);

    // Matching gestureId sets flutterWonGesture.
    view.onFlutterWonGesture(100);
    assertTrue(view.getFlutterWonGesture());

    // Subsequent move event triggers unbuffered dispatch.
    final MotionEvent moveEvent =
        MotionEvent.obtain(100, 101, MotionEvent.ACTION_MOVE, 10.0f, 10.0f, 0);
    view.onTouchEvent(moveEvent);
    assertEquals(moveEvent, lastRequestedEvent[0]);
    assertFalse(view.getFlutterWonGesture());
  }

  @Test
  public void pushRuntimeShaderFilter_storesOutermostFilter() {
    final FlutterMutatorsStack stack = new FlutterMutatorsStack();
    assertNull(stack.getFinalRuntimeShaderFilter());

    stack.pushRuntimeShaderFilter(1, new float[] {1, 2}, 10, 20, 110, 220);
    stack.pushRuntimeShaderFilter(2, new float[] {3, 4}, 0, 0, 50, 50);

    final FlutterMutatorsStack.RuntimeShaderFilter filter = stack.getFinalRuntimeShaderFilter();
    assertNotNull(filter);
    assertEquals(1, filter.programId);
    assertEquals(10, filter.left);
    assertEquals(20, filter.top);
    assertEquals(100, filter.getWidth());
    assertEquals(200, filter.getHeight());
    assertEquals(2, stack.getMutators().size());
    assertEquals(
        FlutterMutatorsStack.FlutterMutatorType.RUNTIME_SHADER_FILTER,
        stack.getMutators().get(1).getType());
    assertEquals(
        new FlutterMutatorsStack.RuntimeShaderFilter(1, new float[] {1, 2}, 10, 20, 110, 220),
        filter);
    assertFalse(
        new FlutterMutatorsStack.RuntimeShaderFilter(1, new float[] {1, 3}, 10, 20, 110, 220)
            .equals(filter));
  }

  @Test
  @Config(sdk = 34)
  public void readyToDisplay_appliesRuntimeShaderFilterAndLaysOutToFrame() {
    registerFilterProgram();
    final FlutterMutatorView view =
        new FlutterMutatorView(ctx, 1.0f, mock(AndroidTouchProcessor.class));
    final FlutterMutatorsStack stack = makeStackWithFilter(0.3f, 0, 100, 1000, 1100);
    stack.pushClipRect(50, 300, 250, 400);
    final Matrix translate = new Matrix();
    translate.setTranslate(50, 300);
    final float[] values = new float[9];
    translate.getValues(values);
    stack.pushTransform(values);

    view.readyToDisplay(stack, /*left=*/ 50, /*top=*/ 300, /*width=*/ 200, /*height=*/ 200);

    assertTrue(view.hasRuntimeShaderFilter());
    // The view is laid out with the filter's frame as its bounds...
    final FrameLayout.LayoutParams layoutParams = (FrameLayout.LayoutParams) view.getLayoutParams();
    assertEquals(0, layoutParams.leftMargin);
    assertEquals(100, layoutParams.topMargin);
    assertEquals(1000, layoutParams.width);
    assertEquals(1000, layoutParams.height);
    // ...and the platform view is drawn at the same position on screen as before.
    final Matrix expected = new Matrix();
    expected.setTranslate(50, 200);
    assertEquals(expected, view.getPlatformViewMatrix());

    // The clips are applied too (the paths are offset by the frame's origin like the matrix).
    final android.graphics.Canvas canvas = mock(android.graphics.Canvas.class);
    view.draw(canvas);
    verify(canvas).clipPath(any());

    // Removing the filter restores the regular layout.
    view.readyToDisplay(
        new FlutterMutatorsStack(), /*left=*/ 50, /*top=*/ 300, /*width=*/ 200, /*height=*/ 200);
    assertFalse(view.hasRuntimeShaderFilter());
    final FrameLayout.LayoutParams idleParams = (FrameLayout.LayoutParams) view.getLayoutParams();
    assertEquals(50, idleParams.leftMargin);
    assertEquals(300, idleParams.topMargin);
    assertEquals(200, idleParams.width);
    assertEquals(200, idleParams.height);
  }

